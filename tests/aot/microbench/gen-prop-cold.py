#!/usr/bin/env python3
"""Writes prop-cold.mjs.

prop-cold is about the cold end of a property read: the first time a site runs, when its
slot is still empty. That is the case the GetById stub's known-shape dispatch table serves
on ARM64, and that the C++ operation serves everywhere else — the operation doing a full
property lookup (PropertySlot, the prototype chain, the caching machinery) where the stub
does a direct lookup by the object's shape and the site's selector.

A site can only be cold once, so the fixture has to hold many sites and reach each once:
one object literal of SITES properties, one reader function per GROUP, each reader reading
all SITES properties of the object in the module-level binding `o`. `o` is written by
`put()`, another function, so no reader can be handed the literal's fields on the way in
and the reads have to happen. The readers are called once each, from the statements at the
end, so every site's slot is empty at its only access.
"""

import sys
from pathlib import Path

SITES = int(sys.argv[2]) if len(sys.argv) > 2 else 64    # properties of the one object, and sites per reader
GROUPS = int(sys.argv[3]) if len(sys.argv) > 3 else 200  # readers, each reaching SITES sites once

names = [f"p{index:02d}" for index in range(SITES)]

out = [
    "// Generated by gen-prop-cold.py — do not edit by hand.",
    "//",
    "// A property read is cold exactly once, when the site first runs and its slot is",
    "// still empty: the case the GetById stub's known-shape dispatch table serves. A site",
    "// can only be cold once, so the fixture holds GROUPS readers of SITES sites each,",
    "// every one of them reached exactly once, on one object of a shape the image knows.",
    "//",
    "// The object is read back through the module-level binding `o`, which only `put()`",
    "// writes: no reader is handed the literal's fields on the way in, so the reads",
    "// cannot be answered from what the compiler already knows about them.",
    f"const SITES = {SITES};",
    f"const GROUPS = {GROUPS};",
    "",
    "let o;",
    "",
    "function put(i) {",
    "  o = {",
    ",\n".join(f"    {name}: i + {index}" for index, name in enumerate(names)),
    "  };",
    "}",
    "",
]

for group in range(GROUPS):
    rows = [
        " + ".join(f"o.{name}" for name in names[start:start + 8])
        for start in range(0, SITES, 8)
    ]
    out.append(f"function rd{group}() {{")
    out.append("  return (")
    out.append("\n".join(f"    {row} +" for row in rows[:-1]))
    out.append(f"    {rows[-1]}")
    out.append("  ) | 0;")
    out.append("}")
    out.append("")

out.append("let s = 0;")
for group in range(GROUPS):
    out.append(f"put({group});")
    out.append(f"s = (s + rd{group}()) % 1000003;")
out.append('console.log("prop-cold", s);')
out.append("")

text = "\n".join(out)
path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent / "prop-cold.mjs"
path.write_text(text)
print(f"{path}: {text.count(chr(10))} lines, {GROUPS * SITES} sites, {len(text)} bytes")
